"use strict";
const assert=require("node:assert/strict");
const lib=require("./auto-audit.js");
const make=i=>"https://www.facebook.com/profile.php?id="+String(100000000000+i);
const ids=Array.from({length:190},(_,i)=>({profileUrl:make(i+1)}));
const urls=lib.plan([ids[0],...ids,ids[5],{profileUrl:"https://invalid.local"}]);
assert.equal(urls.length,190);
assert.equal(urls[0],make(1));
assert.equal(urls[189],make(190));
let state=lib.create(urls,null);
assert.equal(state.status,"ready");
assert.equal(state.index,0);
assert.equal(state.urls.length,190);
state.index=78;state.usable=13;state.status="paused";
const resumed=lib.create(urls,state);
assert.equal(resumed.index,78);
assert.equal(resumed.usable,13);
assert.equal(resumed.status,"paused");
const changed=lib.create(lib.plan(ids.slice(0,120)),state);
assert.equal(changed.index,0);
assert.equal(changed.urls.length,120);
assert.equal(lib.reuseAttempt({status:"insufficient",at:new Date().toISOString()}),true);
assert.equal(lib.reuseAttempt({status:"rate_limited",at:new Date().toISOString()}),false);
assert.equal(lib.reuseAttempt({status:"network_error",at:"2020-01-01T00:00:00Z"}),false);
assert.equal(lib.metadata({access:"insufficient"},make(1)),null);
assert.equal(lib.metadata({access:"public_metadata",region:"unknown",hasBio:null},make(1)),null);
const known=lib.metadata({access:"public_metadata",region:"local",hasBio:null},make(1));
assert.equal(known.regionContext,"local");
assert(!JSON.stringify(known).includes("birthday"));
assert(!JSON.stringify(known).includes("email"));
assert.equal(lib.halt("rate_limited",0),true);
assert.equal(lib.halt("restricted",0),true);
assert.equal(lib.halt("network_error",2),false);
assert.equal(lib.halt("network_error",3),true);
console.log("VOIDSCAN 190-profile queue, pause/resume and safe metadata limits: PASS");
